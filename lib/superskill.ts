import fs from 'node:fs';
import path from 'node:path';
import { sourceFiles, type FileEntry } from './hash';
import type { SuperDef } from './manifest';
import type { Repo } from './repo';
import { type SkillDir } from './skills';
import { cell } from './readme';

const GUIDE = 'GUIDE.md';

export function stripFrontmatter(text: string): string {
  return text.replace(/\r\n/g, '\n').replace(/^---\n[\s\S]*?\n---\n?/, '').trim();
}

function collapse(s: string): string {
  return s.replace(/\s+/g, ' ').trim();
}

/** Cut at a word boundary so one long member cannot push the others out of the 1024-character limit. */
function clip(s: string, max: number): string {
  if (s.length <= max) return s;
  const cut = s.slice(0, Math.max(0, max - 1));
  return `${cut.slice(0, cut.lastIndexOf(' ') > 0 ? cut.lastIndexOf(' ') : cut.length)}…`;
}

export function generatedDescription(members: SkillDir[]): string {
  const names = members.map((m) => m.name).join(', ');
  const head = `Use for ${names}: `;
  const sep = ' | ';
  // Every member gets an equal share, so each one keeps its trigger words.
  const share = Math.floor((512 - head.length - sep.length * (members.length - 1)) / members.length);
  const parts = members.map((m) => clip(`${m.name}: ${collapse(m.description)}`, share));
  return head + parts.join(sep);
}

/** Below this share per member a generated description cannot carry any trigger words. */
const MIN_SHARE = 90;

/** The bundle as in-memory files. Pure, so `check` can rebuild and compare without writing. */
export function buildSuperFiles(name: string, def: SuperDef, members: SkillDir[]): FileEntry[] {
  if (members.length === 0) throw new Error(`superskill "${name}" needs at least one member`);

  const description = def.description.trim() || generatedDescription(members);
  if (!def.description.trim() && (512 - members.map(m => m.name).join(', ').length) / members.length < MIN_SHARE) {
    throw new Error(`superskill "${name}": ${members.length} members is too many for a generated description. Pass --description`);
  }
  if (description.length > 1024) throw new Error(`superskill "${name}": description is longer than 1024 characters`);
  return buildRouter(name, description, members);
}

function frontmatter(name: string, description: string, members: SkillDir[]): string {
  return [
    '---',
    `name: ${name}`,
    `description: ${JSON.stringify(description)}`,
    '---',
    '',
    `<!-- Generated by my-skills from ${members.map((m) => m.name).join(', ')}. Edit the source skills, then run: bun index.ts -->`,
    '',
    `# ${name}`,
    '',
  ].join('\n') + '\n';
}

/** A router: one line per member, each pointing at that member's own guide, loaded only when it applies. */
function buildRouter(name: string, description: string, members: SkillDir[]): FileEntry[] {
  const files: FileEntry[] = [];
  const rows: string[] = [];
  for (const m of members) {
    const all = sourceFiles(m.abs);
    if (all.some((f) => f.rel === GUIDE)) throw new Error(`superskill "${name}": ${m.name} already has a ${GUIDE}`);
    for (const f of all) {
      if (f.rel === 'SKILL.md') files.push({ rel: `${m.name}/${GUIDE}`, buf: Buffer.from(stripFrontmatter(f.buf.toString('utf8')) + '\n'), mode: f.mode });
      else files.push({ ...f, rel: `${m.name}/${f.rel}` });
    }
    rows.push(`| [${m.name}](${m.name}/${GUIDE}) | ${cell(clip(collapse(m.description), 240))} |`);
  }
  const body = [
    `Routes to ${members.length} guides. Read only the guide needed for the current task; do not load the whole bundle.`,
    'Treat each guide’s folder as its skill root and working directory for relative commands, scripts, and supporting files. References to “this SKILL.md” mean that guide’s GUIDE.md.',
    'When a guide asks for another bundled skill, read its row here instead of searching for a separately installed skill. Load additional guides only when needed.',
    '',
    '| Guide | Use when |',
    '| --- | --- |',
    ...rows,
    '',
  ].join('\n');
  files.push({ rel: 'SKILL.md', buf: Buffer.from(`${frontmatter(name, description, members)}${body}`) });
  return files;
}

/** Resolve member names to skills. Nesting is refused to keep routing and membership unambiguous. */
export function resolveMembers(skills: SkillDir[], names: string[], owner: string): SkillDir[] {
  return names.map((n) => {
    const s = skills.find((x) => x.name === n);
    if (!s) throw new Error(`superskill "${owner}": member "${n}" does not exist`);
    if (s.root !== 'skills') throw new Error(`superskill "${owner}": "${n}" is a superskill, and superskills cannot nest`);
    return s;
  });
}

export function writeSuper(repo: Repo, name: string, files: FileEntry[]): void {
  const dir = path.join(repo.superDir, name);
  fs.rmSync(dir, { recursive: true, force: true });
  for (const f of files) {
    const dest = path.join(dir, f.rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, f.buf);
    if (f.mode !== undefined) fs.chmodSync(dest, f.mode);
  }
}
