#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = ["pillow==11.3.0"]
# ///
"""Generate parity.md from the golden traces: breadth, behaviour and visual, measured.

Usage: parity.py [CLONE_DIR] [--traces traces] [--features research/features.json] [--pixel-threshold 2.0]

  behaviour  experiments whose notes match (diff.compare_notes) / experiments with both traces
  visual     steps whose pixel difference is under the threshold / steps compared
  breadth    features marked present / features listed (optional research/features.json:
             {"Next nap prediction": {"present": true, "experiments": ["next_nap_short"]}})

Writes CLONE_DIR/parity.md and parity.json. Exits 1 when a count is lower than in the
previous parity.json (a number already reached is never lowered).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import diff  # noqa: E402


def experiment_result(folder: Path, threshold: float) -> dict | None:
    original, clone = folder / "original", folder / "clone"
    if not (original.is_dir() and clone.is_dir()):
        return None
    problems = diff.compare_notes(diff.load(original / "notes.json", {}), diff.load(clone / "notes.json", {}))
    original_steps, clone_steps = diff.steps(original), diff.steps(clone)
    visual_total = visual_ok = 0
    for name, a in original_steps.items():
        b = clone_steps.get(name)
        if b is None:
            continue
        pixels = diff.compare_screens(a / "screen.png", b / "screen.png", b / "diff.png")
        if pixels is not None:
            visual_total += 1
            visual_ok += pixels <= threshold
    return {"name": folder.name, "behaviour": not problems, "problems": problems,
            "visual_total": visual_total, "visual_ok": visual_ok}


def collect(traces: Path, threshold: float) -> list[dict]:
    results = (experiment_result(p, threshold) for p in sorted(traces.iterdir()) if p.is_dir()) if traces.is_dir() else []
    return [r for r in results if r]


def totals(results: list[dict], features: dict) -> dict:
    return {
        "behaviour_ok": sum(r["behaviour"] for r in results), "behaviour_total": len(results),
        "visual_ok": sum(r["visual_ok"] for r in results), "visual_total": sum(r["visual_total"] for r in results),
        "breadth_ok": sum(1 for f in features.values() if f.get("present")), "breadth_total": len(features),
    }


def regressions(now: dict, before: dict) -> list[str]:
    return [f"{key}: {before[key]} -> {now[key]}" for key in ("behaviour_ok", "visual_ok", "breadth_ok")
            if key in before and now[key] < before[key]]


def render(results: list[dict], features: dict, count: dict) -> str:
    by_name = {r["name"]: r for r in results}
    lines = ["# Parity scorecard", "", "Generated by `parity.py` from `traces/`. Do not edit by hand.", "",
             f"- Breadth: {count['breadth_ok']}/{count['breadth_total']} catalog features present"
             if features else "- Breadth: n/a (no `research/features.json`)",
             f"- Behaviour: {count['behaviour_ok']}/{count['behaviour_total']} experiments match",
             f"- Visual: {count['visual_ok']}/{count['visual_total']} steps under the pixel threshold", ""]
    if features:
        lines += ["| Feature | Experiments | Status |", "|---|---|---|"]
        for feature, info in features.items():
            names = info.get("experiments", [])
            done = [by_name[n] for n in names if n in by_name]
            if not info.get("present"):
                status = "missing"
            elif not names:
                status = "present, no experiments yet"
            else:
                status = f"{sum(r['behaviour'] for r in done)}/{len(names)} match"
            lines.append(f"| {feature} | {', '.join(names) or '-'} | {status} |")
        lines.append("")
    failing = [r for r in results if not r["behaviour"]]
    if failing:
        lines += ["## Failing experiments", ""]
        for r in failing:
            lines += [f"- `{r['name']}`: " + "; ".join(r["problems"])]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("clone_dir", nargs="?", type=Path, default=Path("."))
    parser.add_argument("--traces", type=Path)
    parser.add_argument("--features", type=Path)
    parser.add_argument("--pixel-threshold", type=float, default=2.0)
    args = parser.parse_args()
    traces = args.traces or args.clone_dir / "traces"
    features = diff.load(args.features or args.clone_dir / "research/features.json", {})
    results = collect(traces, args.pixel_threshold)
    count = totals(results, features)
    before = diff.load(args.clone_dir / "parity.json", {})
    (args.clone_dir / "parity.md").write_text(render(results, features, count))
    lost = regressions(count, before)
    if not lost:  # keep the best numbers reached until a regression is fixed
        (args.clone_dir / "parity.json").write_text(json.dumps(count, indent=1) + "\n")
    print(render(results, features, count))
    if lost:
        print("REGRESSION vs parity.json: " + ", ".join(lost), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
